#!/usr/bin/env python3
"""Generate Tiva C level registry from authored levels/*.json.

The Pi reads the same JSON directly. This script does not require pygame.
Run from any directory: python3 tools/generate_levels.py [--check]
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEVELS_DIR = ROOT / "levels"
HEADER = ROOT / "include" / "level_data.h"
SOURCE = ROOT / "src" / "level_data.c"
ITEM_TYPES_FILE = ROOT / "config" / "item_types.json"


def integer(value, field, minimum, maximum):
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError(f"{field} must be an integer in [{minimum}, {maximum}]")
    return value

def read_item_types():
    return json.loads(
        ITEM_TYPES_FILE.read_text(encoding="utf-8")
    )["types"]

def read_levels():
    paths = sorted(LEVELS_DIR.glob("*.json"))
    if not paths:
        raise ValueError("No level JSON files in levels/")

    item_types = read_item_types()
    levels = []
    ids = set()
    symbols = set()
    for path in paths:
        data = json.loads(path.read_text(encoding="utf-8"))
        ident = integer(data["id"], f"{path.name}: id", 0, 255)
        symbol = data["symbol"]
        if not isinstance(symbol, str) or not re.fullmatch(r"[A-Z][A-Z0-9_]*", symbol):
            raise ValueError(f"{path.name}: symbol must be C-safe uppercase identifier")
        if ident in ids or symbol in symbols:
            raise ValueError(f"{path.name}: duplicate ID or symbol")
        ids.add(ident)
        symbols.add(symbol)

        width = integer(data["width"], f"{path.name}: width", 1, 32767)
        height = integer(data["height"], f"{path.name}: height", 1, 32767)
        spawn = data["spawn"]
        if not isinstance(spawn, list) or len(spawn) != 2:
            raise ValueError(f"{path.name}: spawn must be [x, y]")
        sx = integer(spawn[0], f"{path.name}: spawn x", 0, width - 1)
        sy = integer(spawn[1], f"{path.name}: spawn y", 0, height - 1)

        solids = data["solids"]
        if not isinstance(solids, list):
            raise ValueError(f"{path.name}: solids must be a list")
        for i, solid in enumerate(solids):
            rect = solid["rect"]
            if not isinstance(rect, list) or len(rect) != 4:
                raise ValueError(f"{path.name}: solid {i} needs rect [x,y,w,h]")
            x = integer(rect[0], f"{path.name}: solid {i} x", 0, width-1)
            y = integer(rect[1], f"{path.name}: solid {i} y", 0, height-1)
            w = integer(rect[2], f"{path.name}: solid {i} width", 1, 65535)
            h = integer(rect[3], f"{path.name}: solid {i} height", 1, 65535)
            if x+w > width or y+h > height:
                raise ValueError(f"{path.name}: solid {i} extends outside level")
            sprite = solid.get("sprite")
            if sprite not in (None, "brick"):
                raise ValueError(f"{path.name}: unsupported sprite '{sprite}' (add renderer mapping first)")
            if sprite == "brick" and (w % 16 or h % 16):
                raise ValueError(f"{path.name}: brick dimensions must be multiples of 16")
        if not isinstance(data.get("background"), str) or not data["background"]:
            raise ValueError(f"{path.name}: background folder required")
        integer(data.get("background_frame", 0), f"{path.name}: background frame", 0, 255)

        # goal validation
        goal = data.get("goal")
        if goal is not None:
            if not isinstance(goal, dict):
                raise ValueError(f"{path.name}: goal must be an object")

            if goal.get("type") != "flagpole":
                raise ValueError(f"{path.name}: unsupported goal type")

            rect = goal.get("rect")

            if not isinstance(rect, list) or len(rect) != 4:
                raise ValueError(f"{path.name}: goal needs rect [x, y, w, h]")

            gx = integer(rect[0], "goal x", 0, width - 1)
            gy = integer(rect[1], "goal y", 0, height - 1)
            gw = integer(rect[2], "goal width", 1, width)
            gh = integer(rect[3], "goal height", 1, height)

            if gx + gw > width or gy + gh > height:
                raise ValueError(f"{path.name}: goal extends outside level")

        # Check item types against the shared registry
        for item in data.get("items", []):
            if item["type"] not in item_types:
                raise ValueError(f"Unknown item: {item['type']}")

        levels.append(data)
    return sorted(levels, key=lambda item: item["id"])


def generate(levels):
    header = [
        "/* GENERATED by tools/generate_levels.py; DO NOT EDIT. */",
        "#ifndef LEVEL_DATA_H", "#define LEVEL_DATA_H", "",
        "#include <stddef.h>", "#include <stdint.h>", "",
        "typedef enum {",
    ]
    for level in levels:
        header.append(f"    LEVEL_ID_{level['symbol']} = {level['id']},")
    header += [
        "} LevelID;", "",
        "typedef struct {",
        "    int16_t x;", "    int16_t y;",
        "    uint16_t width;", "    uint16_t height;",
        "} LevelSolid;", "",
    ]
    item_types = read_item_types()
    header += ["typedef enum {"]
    for name, definition in item_types.items():
        header.append(f"    ITEM_TYPE_{name.upper()} = {definition['id']},")
    header += [
        "} item_type;", "",
        "typedef struct {",
        "    item_type type;",
        "    LevelSolid rect;",
        "} LevelItem;", "",
        "typedef struct {",
        "    LevelID id;", "    uint16_t width;", "    uint16_t height;",
        "    float spawn_x;", "    float spawn_y;",
        "    const LevelSolid *solids;", "    size_t solid_count;",
        "   LevelSolid goal;",
        "   uint8_t has_goal;",
        "    const LevelItem *items;",
        "    size_t item_count;",
        "} LevelDefinition;", "",
        "const LevelDefinition *level_get(LevelID id);",
        "const LevelDefinition *level_get_next(LevelID id);",
        "",
        "#endif", "",
    ]

    source = [
        "/* GENERATED by tools/generate_levels.py; DO NOT EDIT. */",
        '#include "level_data.h"', "", "#define ARRAY_COUNT(a) (sizeof(a) / sizeof((a)[0]))", "",
    ]
    for level in levels:
        arr = f"level_{level['id']}_solids"
        if level["solids"]:
            source.append(f"static const LevelSolid {arr}[] = {{")
            for solid in level["solids"]:
                x, y, w, h = solid["rect"]
                source.append(f"    {{{x}, {y}, {w}, {h}}},")
            source += ["};", ""]

    for level in levels:
        items = level.get("items", [])
        if items:
            source.append(f"static const LevelItem level_{level['id']}_items[] = {{")
            for item in items:
                x, y, w, h = item["rect"]
                source.append(
                    f"    {{ITEM_TYPE_{item['type'].upper()}, {{{x}, {y}, {w}, {h}}}}},"
                )
            source += ["};", ""]

    source.append("static const LevelDefinition levels[] = {")

    for level in levels:
        arr = f"level_{level['id']}_solids"

        ptr, count = (
            (arr, f"ARRAY_COUNT({arr})")
            if level["solids"]
            else ("NULL", "0u")
        )

        items = level.get("items", [])
        item_arr = f"level_{level['id']}_items"
        item_ptr, item_count = (
            (item_arr, f"ARRAY_COUNT({item_arr})")
            if items
            else ("NULL", "0u")
        )

        goal = level.get("goal")

        if goal is not None:
            gx, gy, gw, gh = goal["rect"]
            goal_data = f"{{{gx}, {gy}, {gw}, {gh}}}"
            has_goal = "1u"
        else:
            goal_data = "{0, 0, 0, 0}"
            has_goal = "0u"

        source.append(
            f"    {{LEVEL_ID_{level['symbol']}, "
            f"{level['width']}, {level['height']}, "
            f"{level['spawn'][0]}.0f, "
            f"{level['spawn'][1]}.0f, "
            f"{ptr}, {count}, "
            f"{goal_data}, {has_goal}, {item_ptr}, {item_count}}},"
        )

    source += [
        "};", "",
        "const LevelDefinition *level_get(LevelID id) {",
        "    size_t i;",
        "    for (i = 0; i < ARRAY_COUNT(levels); ++i) {",
        "        if (levels[i].id == id) {", "            return &levels[i];",
        "        }", "    }", "    return NULL;", "}", "",
    ]
    source += [
        "const LevelDefinition *level_get_next(LevelID id) {",
        "   size_t i;",
        "   for(i = 0; i < ARRAY_COUNT(levels); ++i){",
        "       if(levels[i].id == id){",
        "           if(i + 1u < ARRAY_COUNT(levels)){",
        "               return &levels[i + 1u];",
        "           }",
        "           return NULL;",
        "       }",
        "   }",
        "   return NULL;",
        "}",
        "",
    ]
    max_items = max(1, *(len(level.get("items", [])) for level in levels))
    header.insert(
        header.index("#endif"),
        f"#define LEVEL_MAX_ITEMS {max_items}"
    )
    return "\n".join(header), "\n".join(source)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated C files are out of date")
    args = parser.parse_args()
    try:
        levels = read_levels()
        expected = generate(levels)
        files = ((HEADER, expected[0]), (SOURCE, expected[1]))
        stale = [p for p, content in files if not p.exists() or p.read_text(encoding="utf-8") != content]
        if args.check:
            if stale:
                print("Stale generated files: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
                return 1
            print(f"Level data current: {len(levels)} level(s)")
        else:
            for path, content in files:
                path.write_text(content, encoding="utf-8", newline="\n")
            print(f"Generated level_data.h and level_data.c for {len(levels)} level(s)")
        return 0
    except (ValueError, KeyError, OSError, json.JSONDecodeError) as exc:
        print(f"Level generation error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
